"""Collect training + simulation + synthesis numbers into results/summary.md and .csv
(every number is read from a generated file; nothing typed by hand)."""
import os, re, json, glob, csv

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rows = []
for mdir in sorted(glob.glob(os.path.join(ROOT, "models", "exp*")),
                   key=lambda p: json.load(open(os.path.join(p, "result.json")))["width"]):
    name = os.path.basename(mdir)
    r = json.load(open(os.path.join(mdir, "result.json")))
    f = os.path.join(ROOT, "fpga", name)
    row = dict(model=name, width=r["width"], depth=r["depth"], gates=r["gates_total"],
               speed_acc=round(100 * r["test_speed_acc"], 2), steer_acc=round(100 * r["test_steer_acc"], 2),
               both_acc=round(100 * r["test_both_acc"], 2))
    logs = sorted(glob.glob(os.path.join(ROOT, "results", "logs", f"fpga_{name}_*.log")))
    if logs:
        t = open(logs[-1]).read()
        m = re.search(r"RESULT vectors=(\d+) mismatches=(\d+) (\w+)", t)
        row["icarus"] = f"{m.group(3)} ({m.group(2)}/{m.group(1)} mismatches)" if m else "n/a"
    st = os.path.join(f, "core_stat.txt")
    if os.path.exists(st):
        s = open(st).read()
        def cnt(pat):
            return sum(int(n) for n, c in re.findall(r"^\s+(\d+)\s+(\S+)\s*$", s, re.M) if re.fullmatch(pat, c))
        row["core_LUT"] = cnt(r"LUT\d")
        row["core_MUX2_LUTx"] = cnt(r"MUX2_LUT\d")
        row["core_ALU"] = cnt(r"ALU")
        row["core_FF"] = cnt(r"DFF\w*")
        row["core_BSRAM"] = cnt(r"(SP|SPX9|DP|DPB|DPX9B|SDPB|SDPX9B|pROM\w*|RAM16\w*)")
        row["core_DSP"] = cnt(r"MULT\w*|ALU54D|PADD\w*")
    pl = os.path.join(f, "pnr.log")
    if os.path.exists(pl):
        p = open(pl).read()
        fm = re.findall(r"Max frequency for clock '[^']+': ([\d.]+) MHz", p)
        if fm:
            row["fmax_MHz"] = float(fm[-1])
            row["reg_to_reg_ns"] = round(1000 / float(fm[-1]), 2)
        u = re.search(r"LUT4:\s+(\d+)/\s*(\d+)", p)
        if u: row["pnr_LUT4"] = f"{u.group(1)}/{u.group(2)}"
    rows.append(row)

base = json.load(open(os.path.join(ROOT, "results", "baseline_mlp.json")))
os.makedirs(os.path.join(ROOT, "results"), exist_ok=True)
keys = sorted({k for r in rows for k in r}, key=lambda k: list(rows[0].keys()).index(k)
              if k in rows[0] else 99)
with open(os.path.join(ROOT, "results", "summary.csv"), "w", newline="") as fh:
    w = csv.DictWriter(fh, fieldnames=keys); w.writeheader(); w.writerows(rows)
md = ["# Exp-01 results (auto-generated by python/collect_results.py)", "",
      "| " + " | ".join(keys) + " |", "|" + "---|" * len(keys)]
for r in rows:
    md.append("| " + " | ".join(str(r.get(k, "")) for k in keys) + " |")
md += ["", "Baseline, weight-based MLP 4-6-6-6-6-9 on the same data "
       f"({base['params']} params): float both={100*base['float_both']:.2f}%, "
       f"int8 both={100*base['int8_both']:.2f}% "
       f"(speed {100*base['int8_speed']:.2f}%, steer {100*base['int8_steer']:.2f}%)."]
open(os.path.join(ROOT, "results", "summary.md"), "w").write("\n".join(md) + "\n")
print("\n".join(md))
