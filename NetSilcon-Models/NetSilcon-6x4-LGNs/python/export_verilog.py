"""
Export a trained NetSilcon-6x4-LGN netlist to PURE COMBINATIONAL Verilog
(only continuous assignments: no always blocks, no registers, no memory)
(every bit is its own scalar wire so Icarus simulates it fast)
+ golden test vectors from the Python hard model for the Icarus testbench.

usage: python export_verilog.py exp01_w360
"""
import sys, os, json
import numpy as np
import dataset as D
from lgn import VEXPR, COEF

name = sys.argv[1]
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
mdir = os.path.join(ROOT, "models", name)
z = np.load(os.path.join(mdir, "netlist.npz"))
thresh, heads, group = z["thresh"], [int(h) for h in z["heads"]], int(z["group"])
depth = len([k for k in z.files if k[0] == "g" and k[1:].isdigit()])
mod = f"netsilcon_6x4_lgn_{name}"
sens = ["fl", "fr", "rl", "rr"]
nT = len(thresh)

v = []
v.append(f"// {mod}.v  --  auto-generated by NetSilcon-6x4-LGNs/python/export_verilog.py")
v.append("// Pure combinational logic gate network: NO registers, NO memory, NO multipliers.")
v.append("// The learned 'weights' are the gate types and the wiring below.")
v.append("`default_nettype none")
v.append(f"module {mod} (")
v.append("    input  wire [7:0] fl, fr, rl, rr,   // corner distance sensors, cm")
v.append("    output wire [1:0] speed,             // 0 stop,1 slow,2 medium,3 fast")
v.append("    output wire [2:0] steer              // 0 HL,1 L,2 straight,3 R,4 HR")
v.append(");")
nin = 4 * nT
v.append(f"    // ---- thermometer encoder: constant comparators ({nin} bits) ----")
for i, s in enumerate(sens):
    for k, t in enumerate(thresh):
        v.append(f"    wire x_{i*nT+k} = ({s} > 8'd{int(t)});")
prev = "x"
for l in range(depth):
    ia, ib, g = z[f"ia{l}"], z[f"ib{l}"], z[f"g{l}"]
    W = len(g)
    v.append(f"    // ---- logic layer {l} ({W} gates) ----")
    for j in range(W):
        e = VEXPR[g[j]].format(a=f"{prev}_{ia[j]}", b=f"{prev}_{ib[j]}")
        v.append(f"    wire l{l}_{j} = {e};")
    prev = f"l{l}"
cw = int(np.ceil(np.log2(group + 1)))
v.append(f"    // ---- GroupSum: popcount of {group} gates per class ----")
ncls = sum(heads)
for c in range(ncls):
    # balanced adder tree (fast in simulation, same logic after synthesis)
    terms = [f"{prev}_{c*group+j}" for j in range(group)]
    lvl = 0
    while len(terms) > 1:
        nxt = []
        for k in range(0, len(terms), 2):
            if k + 1 < len(terms):
                wn = f"p{c}_{lvl}_{k//2}"
                v.append(f"    wire [{cw-1}:0] {wn} = {terms[k]} + {terms[k+1]};")
                nxt.append(wn)
            else:
                nxt.append(terms[k])
        terms, lvl = nxt, lvl + 1
    v.append(f"    wire [{cw-1}:0] cnt{c} = {terms[0]};")


def argmax(first, n, outname, ow):
    # strict '>' so ties keep the lowest index (same as numpy argmax)
    v.append(f"    // argmax over classes {first}..{first+n-1}")
    v.append(f"    wire [{cw-1}:0] {outname}_v0 = cnt{first};")
    v.append(f"    wire [{ow-1}:0] {outname}_i0 = {ow}'d0;")
    for k in range(1, n):
        c = f"cnt{first+k}"
        v.append(f"    wire {outname}_gt{k} = ({c} > {outname}_v{k-1});")
        v.append(f"    wire [{cw-1}:0] {outname}_v{k} = {outname}_gt{k} ? {c} : {outname}_v{k-1};")
        v.append(f"    wire [{ow-1}:0] {outname}_i{k} = {outname}_gt{k} ? {ow}'d{k} : {outname}_i{k-1};")
    v.append(f"    assign {outname} = {outname}_i{n-1};")


argmax(0, heads[0], "speed", 2)
argmax(heads[0], heads[1], "steer", 3)
v.append("endmodule")
v.append("`default_nettype wire")

fdir = os.path.join(ROOT, "fpga", name)
os.makedirs(fdir, exist_ok=True)
open(os.path.join(fdir, f"{mod}.v"), "w").write("\n".join(v) + "\n")

# ---- golden vectors from the Python hard model (bit-exact reference) ----
from lgn import LGN
rng = np.random.default_rng(7)
s, _, _ = D.make(4000, seed=3)
edge = np.array([[0, 0, 0, 0], [255, 255, 255, 255], [0, 255, 0, 255], [255, 0, 255, 0],
                 [8, 9, 8, 9], [16, 15, 200, 3]], dtype=np.uint8)
rnd = rng.integers(0, 256, (90, 4)).astype(np.uint8)
s = np.concatenate([edge, rnd, s])
X = D.encode(s).astype(np.uint8)
x = X
for l in range(depth):
    c = COEF[z[f"g{l}"]]; a, b = x[:, z[f"ia{l}"]], x[:, z[f"ib{l}"]]
    x = (c[:, 0] + c[:, 1] * a + c[:, 2] * b + c[:, 3] * a * b).astype(np.uint8)
cnt = x.reshape(len(x), -1, group).sum(2)
sp = cnt[:, :heads[0]].argmax(1); st = cnt[:, heads[0]:].argmax(1)
with open(os.path.join(fdir, "golden.hex"), "w") as f:
    for r, a, b in zip(s, sp, st):
        f.write(f"{r[0]:02x}{r[1]:02x}{r[2]:02x}{r[3]:02x}{a:01x}{b:01x}\n")
tsp, tst = D.teacher(s)
info = dict(module=mod, vectors=len(s), depth=depth, heads=heads, group=group,
            golden_vs_teacher_both=float(((sp == tsp) & (st == tst)).mean()))
json.dump(info, open(os.path.join(fdir, "export.json"), "w"), indent=2)

# ---- Icarus testbench ----
tb = f"""// tb_{mod}.v -- compares the Verilog against Python golden vectors (bit-exact)
`timescale 1ns/1ps
module tb;
    reg  [7:0] fl, fr, rl, rr;
    wire [1:0] speed;  wire [2:0] steer;
    reg  [39:0] mem [0:{len(s)-1}];
    integer i, err;
    {mod} dut(.fl(fl), .fr(fr), .rl(rl), .rr(rr), .speed(speed), .steer(steer));
    initial begin
        $readmemh("golden.hex", mem);
        err = 0;
        for (i = 0; i < {len(s)}; i = i + 1) begin
            {{fl, fr, rl, rr}} = mem[i][39:8];
            #10;
            if (speed !== mem[i][5:4] || steer !== mem[i][2:0]) begin
                err = err + 1;
                if (err < 10) $display("MISMATCH %0d in=%h got sp=%0d st=%0d exp sp=%0d st=%0d",
                                       i, mem[i][39:8], speed, steer, mem[i][5:4], mem[i][2:0]);
            end
        end
        $display("RESULT vectors=%0d mismatches=%0d %s", {len(s)}, err, (err==0) ? "PASS" : "FAIL");
        $finish;
    end
endmodule
"""
open(os.path.join(fdir, f"tb_{mod}.v"), "w").write(tb)

# ---- measurement wrapper (ONLY for timing: adds in/out registers around the core) ----
wrap = f"""// timing_wrapper.v -- FOR MEASUREMENT ONLY.
// Shift 32 input bits in serially, run the combinational core, capture outputs.
// The registers here exist only so nextpnr can time reg -> core -> reg.
// The core itself ({mod}) has zero registers.
module timing_wrapper (input wire clk, input wire din, output wire dout);
    reg [31:0] sh = 32'd0;
    reg [4:0]  q  = 5'd0;
    wire [1:0] speed; wire [2:0] steer;
    always @(posedge clk) sh <= {{sh[30:0], din}};
    {mod} core(.fl(sh[31:24]), .fr(sh[23:16]), .rl(sh[15:8]), .rr(sh[7:0]),
               .speed(speed), .steer(steer));
    always @(posedge clk) q <= {{speed, steer}};
    assign dout = ^q;
endmodule
"""
open(os.path.join(fdir, "timing_wrapper.v"), "w").write(wrap)
open(os.path.join(fdir, "tangnano20k.cst"), "w").write(
    'IO_LOC "clk" 4;\nIO_PORT "clk" IO_TYPE=LVCMOS33;\n'
    'IO_LOC "din" 88;\nIO_PORT "din" IO_TYPE=LVCMOS33;\n'
    'IO_LOC "dout" 15;\nIO_PORT "dout" IO_TYPE=LVCMOS33;\n')
print(json.dumps(info))
