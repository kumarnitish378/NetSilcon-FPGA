"""Quantize the trained model to the exact integer math NetSilcon-6x4 uses,
then export everything the Verilog needs.

Hardware math for every neuron (bit-exact with rtl/nn_layer.v):
    acc = bias16 + sum( x_i[int8] * w_i[int8] )        # 20-bit signed accumulator
    if hidden layer:  acc = max(acc, 0)                 # ReLU (sign-bit trick)
    y   = (acc + 2^(s-1)) >> s                          # round + arithmetic right shift
    y   = clamp(y, 0..127)   hidden layers
          clamp(y, -128..127) output layer

Run:  python quantize.py      (after train.py)
Outputs in ../gen/ :
    weights.mem      144 weights, 2 hex digits each (8-bit two's complement)
    biases.mem       26 biases, 4 hex digits each (16-bit two's complement)
    netsilcon_params.vh   requantization shifts as Verilog localparams
    test_in.mem / test_out.mem   golden vectors for the testbench
    model_report.txt
"""
import os
import numpy as np
from data import make, to_int8, RANGES, NAMES

SIZES = [4, 6, 6, 6, 6, 2]
GEN = os.path.join(os.path.dirname(__file__), "..", "gen")
os.makedirs(GEN, exist_ok=True)
ACC_BITS = 20
ACC_MIN, ACC_MAX = -(1 << (ACC_BITS - 1)), (1 << (ACC_BITS - 1)) - 1

f = np.load("float_weights.npz")
L = len(SIZES) - 1
Wf = [f[f"arr_{i}"] for i in range(L)]
bf = [f[f"arr_{i + L}"] for i in range(L)]


def int_forward(Wq, bq, shifts, xq, trace=False):
    """Bit-exact integer reference. xq: (n, 4) ints in 0..127."""
    a = xq.astype(np.int64)
    accs = []
    for l in range(L):
        acc = a @ Wq[l].T.astype(np.int64) + bq[l].astype(np.int64)
        accs.append(acc)
        assert acc.min() >= ACC_MIN and acc.max() <= ACC_MAX, f"layer {l+1} overflows {ACC_BITS}-bit accumulator"
        s = shifts[l]
        hidden = l < L - 1
        if hidden:
            acc = np.maximum(acc, 0)
        half = (1 << (s - 1)) if s > 0 else 0
        y = (acc + half) >> s                      # numpy >> on int64 = arithmetic shift (floor), same as Verilog >>>
        a = np.clip(y, 0, 127) if hidden else np.clip(y, -128, 127)
    return (a, accs) if trace else a


# ---- calibrate: choose int8 weights, int16 biases and power-of-two shifts layer by layer
Xcal, _ = make(20000, seed=1)
xcal = to_int8(Xcal)
s_in = 1.0 / 127.0                 # input scale: q = x * 127
Wq, bq, shifts = [], [], []
a_cal = xcal.astype(np.int64)
for l in range(L):
    s_w = np.abs(Wf[l]).max() / 127.0
    W = np.clip(np.round(Wf[l] / s_w), -127, 127).astype(np.int64)
    b = np.round(bf[l] / (s_in * s_w)).astype(np.int64)
    assert np.abs(b).max() <= 32767, f"layer {l+1} bias does not fit int16"
    acc = a_cal @ W.T + b
    hidden = l < L - 1
    peak = np.maximum(acc, 0).max() if hidden else np.abs(acc).max()
    s = max(0, int(np.ceil(np.log2(max(peak, 1) / 127.0))))
    Wq.append(W); bq.append(b); shifts.append(s)
    half = (1 << (s - 1)) if s > 0 else 0
    y = (np.maximum(acc, 0) if hidden else acc) + half >> s
    a_cal = np.clip(y, 0, 127) if hidden else np.clip(y, -128, 127)
    s_in = s_in * s_w * (2 ** s)   # scale of this layer's output

# ---- evaluate float vs integer model
Xte, yte = make(4000, seed=2)
xte = to_int8(Xte)


def float_forward(x):
    a = x / 127.0
    for l in range(L):
        z = a @ Wf[l].T + bf[l]
        a = np.maximum(z, 0) if l < L - 1 else z
    return a


acc_float = (float_forward(xte).argmax(1) == yte).mean()
out_int, accs = int_forward(Wq, bq, shifts, xte, trace=True)
pred_int = (out_int[:, 1] > out_int[:, 0]).astype(int)   # hardware decision: fault if y1 > y0
acc_int = (pred_int == yte).mean()


# ---- export for Verilog
def hx(v, bits):
    return format(int(v) & ((1 << bits) - 1), f"0{bits // 4}x")


w_all = np.concatenate([W.reshape(-1) for W in Wq])        # order: layer, neuron j, input i  -> index j*N_IN + i
b_all = np.concatenate(bq)
assert len(w_all) == 144 and len(b_all) == 26
open(os.path.join(GEN, "weights.mem"), "w").write("\n".join(hx(v, 8) for v in w_all) + "\n")
open(os.path.join(GEN, "biases.mem"), "w").write("\n".join(hx(v, 16) for v in b_all) + "\n")
with open(os.path.join(GEN, "netsilcon_params.vh"), "w") as fh:
    fh.write("// Generated by model/quantize.py - requantization right-shifts per layer\n")
    for l, s in enumerate(shifts):
        fh.write(f"localparam SHIFT{l+1} = {s};\n")

# golden vectors: 512 test-set samples + corner cases
rng = np.random.default_rng(7)
corners = np.array([[0, 0, 0, 0], [127, 127, 127, 127], [127, 0, 0, 127], [0, 127, 127, 0]]
                   + rng.integers(0, 128, (60, 4)).tolist())
vin = np.concatenate([xte[:512], corners])
vout = int_forward(Wq, bq, shifts, vin)
with open(os.path.join(GEN, "test_in.mem"), "w") as fh:
    for x in vin:   # x0 in bits [7:0] ... x3 in bits [31:24]
        fh.write(hx((x[3] << 24) | (x[2] << 16) | (x[1] << 8) | x[0], 32) + "\n")
with open(os.path.join(GEN, "test_out.mem"), "w") as fh:
    for y in vout:  # y0 in bits [7:0], y1 in bits [15:8]
        fh.write(hx(((int(y[1]) & 0xFF) << 8) | (int(y[0]) & 0xFF), 16) + "\n")
open(os.path.join(GEN, "num_vectors.vh"), "w").write(f"localparam NUM_VECTORS = {len(vin)};\n")

report = [
    "NetSilcon-6x4 model report",
    "==========================",
    f"Topology            : {' -> '.join(map(str, SIZES))}",
    f"Weights / biases    : {len(w_all)} x int8 / {len(b_all)} x int16  ({len(w_all)*8 + len(b_all)*16} bits)",
    f"Shifts per layer    : {shifts}",
    f"Peak |accumulator|  : {[int(np.abs(a).max()) for a in accs]}  (limit {ACC_MAX}, {ACC_BITS}-bit)",
    f"Float accuracy      : {acc_float*100:.2f}%",
    f"Int8 accuracy       : {acc_int*100:.2f}%   (on 4000 test samples)",
    f"Golden vectors      : {len(vin)}",
    "",
    "Input encoding      : q = round(value / range * 127), clipped 0..127",
] + [f"   x{i} {n:10s} range 0..{r:g}" for i, (n, r) in enumerate(zip(NAMES, RANGES))] + [
    "Output              : y0 = healthy score, y1 = fault score  ->  FAULT if y1 > y0",
]
open(os.path.join(GEN, "model_report.txt"), "w").write("\n".join(report) + "\n")
print("\n".join(report))
