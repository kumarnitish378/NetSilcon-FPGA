"""Grade the v1 and v2 pump models with the same grader -> results/v1_vs_v2.md"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import nslm, grade as GR
ROOT = GR.ROOT
rows = ["# LM-0 pump model: v1 vs v2 (auto-generated by compare_models.py)", "",
        "Same grader for both: blank context, 260 questions per set, the answer must be valid for the topic.", "",
        "| model | CRC-32 | correct, trained wordings | correct, held-out wordings |", "|---|---|---|---|"]
for name, f in (("v1: 605k chars, few wordings", "pump_v1.json"), ("v2: 2.9M chars, many wordings, QAT", "pump.json")):
    lm = nslm.LM.from_json(json.load(open(os.path.join(ROOT, "models", "pump", f))))
    r = GR.grade(lm)
    s, u = r["seen"], r["unseen"]
    rows.append(f"| {name} | `{lm.crc32():08X}` | {s['correct']}/{s['total']} ({100*s['correct']/s['total']:.1f} %) | "
                f"{u['correct']}/{u['total']} ({100*u['correct']/u['total']:.1f} %) |")
open(os.path.join(ROOT, "results", "v1_vs_v2.md"), "w").write("\n".join(rows) + "\n")
print("\n".join(rows))
