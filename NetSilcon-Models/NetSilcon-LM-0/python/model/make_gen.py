"""
Write everything the FPGA and the testbenches need from a model file:
  fpga/gen/wmem_00..31.mem   weight/bias RAM contents (32 x 512 x 16 bit)
  fpga/gen/emb.mem           embedding ROM (512 x 8 bit, symbol*8 + d)
  fpga/gen/nslm_model.vh     shifts + CRC as Verilog constants
  fpga/gen/test_ctx.mem      golden contexts (32 symbols x 6 bit, newest in bits 5:0)
  fpga/gen/test_logits.mem   expected 42 int8 logits (logit 0 in bits 7:0) and argmax
  fpga/gen/chat.mem          conversation script: push prompt chars, generate, expected answer
  fpga/gen/num_vectors.vh
usage: python make_gen.py [models/pump/pump.json]
"""
import json, os, sys
import numpy as np
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import nslm

HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(os.path.dirname(HERE))
mpath = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "models", "pump", "pump.json")
lm = nslm.LM.from_json(json.load(open(mpath)))
G = os.path.join(ROOT, "fpga", "gen"); os.makedirs(G, exist_ok=True)

rams = lm.ram_images()
for r in range(nslm.N_RAM):
    open(os.path.join(G, f"wmem_{r:02d}.mem"), "w").write("\n".join(f"{v:04x}" for v in rams[r]) + "\n")
open(os.path.join(G, "emb.mem"), "w").write("\n".join(f"{v:02x}" for v in lm.emb_image()) + "\n")
sh = "".join(f"{s:05b}" for s in reversed(lm.S))
open(os.path.join(G, "nslm_model.vh"), "w").write(
    f"// generated by make_gen.py from {os.path.basename(mpath)}, CRC-32 {lm.crc32():08X}\n"
    f"localparam [19:0] NSLM_SHIFTS = 20'b{sh};   // 4 x 5 bits, layer 0 in bits 4:0\n")

# ---- golden contexts: real test-text windows (from blank and from running context) + random
txt = open(os.path.join(ROOT, "python", "data", "pump_test.txt")).read()
ids = [0] * nslm.CTX + nslm.encode(txt)
rng = np.random.default_rng(11)
pos = rng.choice(len(ids) - nslm.CTX, 700, replace=False)
ctxs = [ids[p:p + nslm.CTX] for p in pos]
ctxs += [list(rng.integers(0, nslm.V, nslm.CTX)) for _ in range(100)]       # random symbols
ctxs += [[0] * nslm.CTX, [nslm.V - 1] * nslm.CTX]                            # edge cases
Y = lm.forward(np.array(ctxs))
for k in range(0, len(ctxs), 97):                                            # cross-check slow model
    assert list(Y[k]) == lm.forward_slow(ctxs[k])
with open(os.path.join(G, "test_ctx.mem"), "w") as f:
    for c in ctxs:
        v = 0
        for p, s in enumerate(c): v |= int(s) << (6 * (nslm.CTX - 1 - p))   # newest in bits 5:0
        f.write(f"{v:048x}\n")
with open(os.path.join(G, "test_logits.mem"), "w") as f:
    for y in Y:
        v = int(np.argmax(y)) << (8 * nslm.V)
        for j, z in enumerate(y): v |= (int(z) & 0xFF) << (8 * j)
        f.write(f"{v:086x}\n")

# ---- chat script: one continuous conversation (context carries over, like the board)
QUESTIONS = ["hello.", "is the pump running?", "what is the pressure?", "flow rate?", "how full is the tank?",
             "motor temp?", "start the pump.", "stop the pump.", "any faults?", "next run?",
             "what can you do?", "who are you?", "run time today?", "is the pump working?"]
ctx = [0] * nslm.CTX; script = []; lines = []
for q in QUESTIONS:
    prompt = f"q: {q}\n"
    script += nslm.encode(prompt)
    ans, ctx = lm.generate(prompt, max_chars=63, ctx=ctx)
    script += [0xC0] + nslm.encode(ans) + [0xFF]
    lines.append(f"q: {q}\n{ans if ans.endswith(chr(10)) else ans + chr(10)}")
open(os.path.join(G, "chat.mem"), "w").write("\n".join(f"{b:02x}" for b in script) + "\n")
open(os.path.join(G, "chat_expected.txt"), "w").write("".join(lines))
# ---- UART board test: bytes typed on the PC and the exact bytes the board must send back
TYPED = ["Q: Hello.\r", "q: is the pump running?\r\n", "Motor temp?\r"]
ctx = [0] * nslm.CTX; uin, uout = [], []
for line in TYPED:
    uin += [ord(c) for c in line]
    body = "".join(c.lower() for c in line if c not in "\r\n")
    uout += [ord(c) for c in body] + [13, 10]
    ans, ctx = lm.generate(body + "\n", max_chars=63, ctx=ctx)
    uout += [ord(c) for c in ans.replace("\n", "\r\n")]
open(os.path.join(G, "uart_in.mem"), "w").write("\n".join(f"{b:02x}" for b in uin) + "\n")
open(os.path.join(G, "uart_out.mem"), "w").write("\n".join(f"{b:02x}" for b in uout) + "\n")
open(os.path.join(G, "num_vectors.vh"), "w").write(
    f"localparam N_VEC = {len(ctxs)};\nlocalparam N_CHAT = {len(script)};\n"
    f"localparam N_UIN = {len(uin)};\nlocalparam N_UOUT = {len(uout)};\n")
print("UART test expects:\n" + bytes(uout).decode().replace("\r", ""))
print(f"model CRC-32 {lm.crc32():08X}, shifts {lm.S}; {len(ctxs)} golden contexts, chat script {len(script)} bytes")
print("".join(lines))
