"""
Write the stimulus files tb_top.v needs (into gen/tb/), from models/*.json.

    python3 scripts/make_tb_load.py

    up_synth.mem      good upload of the synthetic model  (image + CRC-32, 23,339 bytes)
    up_stress.mem     good upload of the stress model
    up_badcrc.mem     stress model with ONE bit flipped in a weight byte (CRC no longer fits)
    up_badshift.mem   synthetic model with shift 4 set to 24 and a CORRECT CRC-32
    test_amax.mem / stress_amax.mem   expected argmax for every golden vector
    tb_load.vh        the CRC-32 values the FPGA must report
"""
import json
import os
import sys
import zlib

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "model"))
import ns64  # noqa: E402

GEN_TB = os.path.join(HERE, "..", "gen", "tb")
MODELS = os.path.join(HERE, "..", "models")


def write_bytes(name, data):
    with open(os.path.join(GEN_TB, name), "w") as f:
        f.writelines(f"{b:02x}\n" for b in data)


def framed(img):
    c = zlib.crc32(img) & 0xFFFFFFFF
    return img + c.to_bytes(4, "little"), c


def main():
    os.makedirs(GEN_TB, exist_ok=True)
    nets, d = {}, {}
    for name in ("synthetic", "stress"):
        d[name] = json.load(open(os.path.join(MODELS, f"{name}.json")))
        nets[name] = ns64.from_json(d[name])

    syn_img, st_img = nets["synthetic"].image(), nets["stress"].image()
    up_syn, c_syn = framed(syn_img)
    up_st, c_st = framed(st_img)

    bad = bytearray(up_st)
    bad[12345] ^= 0x10                       # one bit, inside layer-2 weights
    c_bad_rx = zlib.crc32(bytes(bad[:ns64.IMG_BYTES])) & 0xFFFFFFFF

    bs = bytearray(syn_img)
    bs[ns64.IMG_BYTES - 7 + 3] = 24          # layer-4 shift = 24 (not allowed)
    up_bs, c_bs = framed(bytes(bs))

    write_bytes("up_synth.mem", up_syn)
    write_bytes("up_stress.mem", up_st)
    write_bytes("up_badcrc.mem", bad)
    write_bytes("up_badshift.mem", up_bs)

    for name, prefix in (("synthetic", "test"), ("stress", "stress")):
        y = np.array([v["y"] for v in d[name]["test_vectors"]])
        with open(os.path.join(GEN_TB, f"{prefix}_amax.mem"), "w") as f:
            f.writelines(f"{int(a):x}\n" for a in y.argmax(axis=1))   # numpy: first max

    with open(os.path.join(GEN_TB, "tb_load.vh"), "w") as f:
        f.write("// generated by scripts/make_tb_load.py\n")
        f.write(f"localparam UP_BYTES = {len(up_syn)};\n")
        f.write(f"localparam [31:0] CRC_SYNTH    = 32'h{c_syn:08x};\n")
        f.write(f"localparam [31:0] CRC_STRESS   = 32'h{c_st:08x};\n")
        f.write(f"localparam [31:0] CRC_BAD_RX   = 32'h{c_bad_rx:08x};  // what the FPGA computes over the damaged image\n")
        f.write(f"localparam [31:0] CRC_BADSHIFT = 32'h{c_bs:08x};\n")
    print(f"upload frames: {len(up_syn)} bytes each; CRC synth {c_syn:08X}, stress {c_st:08X}, "
          f"damaged image {c_bad_rx:08X}, bad-shift {c_bs:08X}")


if __name__ == "__main__":
    main()
